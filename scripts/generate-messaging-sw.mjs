/**
 * Generate the Firebase messaging service worker into dist/ at build time.
 *
 * A service worker cannot read import.meta.env, and the Firebase web config is
 * .env-gitignored, so we cannot commit a static worker with the config baked
 * in. Instead this runs after `vite build`, reads the same VITE_FIREBASE_* the
 * app build already consumed (from process.env in CI, or a local .env), and
 * writes the worker with the public config inlined. If the config is absent the
 * worker is still written but self-disables — push simply stays dormant, never
 * broken.
 *
 * The VAPID key is NOT needed here; it is a client-side concern in src/lib/push.ts.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Read a VITE_FIREBASE_* value from process.env, falling back to a local .env. */
function loadEnv() {
  const keys = [
    'VITE_FIREBASE_API_KEY',
    'VITE_FIREBASE_AUTH_DOMAIN',
    'VITE_FIREBASE_PROJECT_ID',
    'VITE_FIREBASE_STORAGE_BUCKET',
    'VITE_FIREBASE_MESSAGING_SENDER_ID',
    'VITE_FIREBASE_APP_ID',
  ];
  const env = {};
  for (const k of keys) env[k] = process.env[k] ?? '';

  const envFile = join(root, '.env');
  if (existsSync(envFile)) {
    for (const line of readFileSync(envFile, 'utf8').split('\n')) {
      const m = /^([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line.trim());
      if (m && keys.includes(m[1]) && !env[m[1]]) {
        env[m[1]] = m[2].replace(/^["']|["']$/g, '');
      }
    }
  }
  return env;
}

const env = loadEnv();
const config = {
  apiKey: env.VITE_FIREBASE_API_KEY,
  authDomain: env.VITE_FIREBASE_AUTH_DOMAIN,
  projectId: env.VITE_FIREBASE_PROJECT_ID,
  storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID,
  appId: env.VITE_FIREBASE_APP_ID,
};

const worker = `/* Generated by scripts/generate-messaging-sw.mjs — do not edit. */
importScripts('https://www.gstatic.com/firebasejs/12.11.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/12.11.0/firebase-messaging-compat.js');

var config = ${JSON.stringify(config)};

if (config.apiKey && config.messagingSenderId) {
  firebase.initializeApp(config);
  var messaging = firebase.messaging();
  messaging.onBackgroundMessage(function (payload) {
    var n = (payload && payload.notification) || {};
    self.registration.showNotification(n.title || 'Calgary Watch', {
      body: n.body || '',
      icon: '/favicon-192.png',
      data: (payload && payload.data) || {},
    });
  });
}

self.addEventListener('notificationclick', function (event) {
  event.notification.close();
  event.waitUntil(clients.openWindow((event.notification.data && event.notification.data.url) || '/map'));
});
`;

const outDir = join(root, 'dist');
if (!existsSync(outDir)) {
  console.warn('[messaging-sw] dist/ not found — run after vite build. Skipping.');
  process.exit(0);
}
writeFileSync(join(outDir, 'firebase-messaging-sw.js'), worker);
console.log(`[messaging-sw] wrote dist/firebase-messaging-sw.js${config.apiKey ? '' : ' (config empty — push dormant)'}`);
